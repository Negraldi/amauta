import { createHash } from 'node:crypto';
import { readdir, readFile, stat, mkdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { writeFileAtomic } from '../core/fsatomic.js';
import { resolveTargets } from '../install/paths.js';

export const REGISTRY_SCHEMA = 'gentle-lite.skill-registry/v1';
const EXCLUDED = new Set(['_shared', 'skill-registry']);
const PROJECT_MARKERS = ['.git', 'package.json', 'pyproject.toml', 'go.mod', 'Cargo.toml', 'pom.xml', 'build.gradle', 'Gemfile', 'composer.json', 'requirements.txt', 'setup.py', 'deno.json', 'mix.exs'];

const sha1 = (data) => createHash('sha1').update(data).digest('hex');
const exists = (p) => stat(p).then(() => true, () => false);

/** True when `cwd` is a real project root: not `/`, not $HOME, and carries a project marker. */
export async function isProjectDir(cwd, home = os.homedir()) {
  const dir = path.resolve(cwd);
  if (dir === path.parse(dir).root || dir === path.resolve(home)) return false;
  for (const marker of PROJECT_MARKERS) if (await exists(path.join(dir, marker))) return true;
  return false;
}

function unquote(v) {
  const t = v.trim();
  return t.length >= 2 && (t[0] === '"' || t[0] === "'") && t.at(-1) === t[0] ? t.slice(1, -1) : t;
}

/** Minimal frontmatter reader: top-level `key: value` plus `>` / `|` block scalars. */
export function parseFrontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  const out = {};
  if (!m) return out;
  const lines = m[1].split(/\r?\n/);
  for (let i = 0; i < lines.length; i += 1) {
    const kv = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(lines[i]);
    if (!kv) continue;
    let value = kv[2];
    if (/^[>|][+-]?$/.test(value.trim())) {
      const parts = [];
      while (i + 1 < lines.length && (/^\s+/.test(lines[i + 1]) || lines[i + 1] === '')) parts.push(lines[(i += 1)].trim());
      value = parts.filter(Boolean).join(' ');
    } else {
      value = unquote(value);
    }
    out[kv[1]] = value;
  }
  return out;
}

async function scanDir(dir, scope) {
  const names = await readdir(dir).catch(() => []);
  const skills = [];
  for (const name of names.sort()) {
    if (EXCLUDED.has(name)) continue;
    const file = path.join(dir, name, 'SKILL.md');
    const st = await stat(file).catch(() => null);
    if (!st?.isFile()) continue;
    const content = await readFile(file);
    const fm = parseFrontmatter(content.toString('utf8'));
    skills.push({
      name: fm.name || name,
      description: fm.description ?? '',
      scope,
      path: file,
      mtime: st.mtimeMs,
      size: st.size,
      hash: sha1(content),
    });
  }
  return skills;
}

export async function collectSkills(cwd, claudeHome) {
  const sources = [path.join(cwd, '.claude', 'skills'), path.join(claudeHome, 'skills')];
  const project = await scanDir(sources[0], 'project');
  const user = await scanDir(sources[1], 'user');
  const byName = new Map();
  for (const s of [...project, ...user]) if (!byName.has(s.name)) byName.set(s.name, s); // project wins
  const skills = [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
  return { skills, sources: (await Promise.all(sources.map(async (s) => ((await exists(s)) ? s : null)))).filter(Boolean) };
}

export const fingerprint = (skills, sources) =>
  sha1(JSON.stringify([REGISTRY_SCHEMA, sources, skills.map((s) => [s.name, s.scope, s.path, s.mtime, s.size, s.hash])]));

const cell = (s) => s.replace(/\s+/g, ' ').replaceAll('|', '\\|').trim();

export function renderRegistry({ repoName, date, sources, skills }) {
  const rows = skills.map((s) => `| \`${s.name}\` | ${cell(s.description)} | ${s.scope} | \`${s.path}\` |`);
  return `# Skill Registry — ${repoName}

<!-- Auto-generated by gentle-lite skill-registry refresh. Run \`gentle-lite skill-registry refresh --force\` to regenerate. -->

Last updated: ${date}

## Sources scanned

${sources.map((s) => `- ${s}`).join('\n') || '- (none)'}

## Contract

**Delegator use only.** This registry is an index, not a summary. Any agent that launches subagents reads it to select relevant skills, then passes exact \`SKILL.md\` paths for the subagent to read before work.

\`SKILL.md\` remains the source of truth. Do not inject generated summaries or compact rules by default; pass paths so subagents load the full runtime contract and preserve author intent.

## Skills

| Skill | Trigger / description | Scope | Path |
| --- | --- | --- | --- |
${rows.join('\n')}

## Loading protocol

1. Match task context and target files against the \`Trigger / description\` column.
2. Pass only the matching \`Path\` values to the subagent under \`## Skills to load before work\`.
3. Instruct the subagent to read those exact \`SKILL.md\` files before reading, writing, reviewing, testing, or creating artifacts.
4. If no matching skill exists, proceed without project skill injection and report \`skill_resolution: none\`.
`;
}

async function ensureGitignore(cwd) {
  const file = path.join(cwd, '.gitignore');
  const current = await readFile(file, 'utf8').catch(() => null);
  if (current === null && !(await exists(path.join(cwd, '.git')))) return;
  if (current !== null && current.split(/\r?\n/).some((l) => l.trim() === '.atl/' || l.trim() === '.atl')) return;
  const prefix = current === null || current === '' ? '' : current.endsWith('\n') ? '\n' : '\n\n';
  await writeFileAtomic(file, `${current ?? ''}${prefix}# Local AI runtime state\n.atl/\n`);
}

/**
 * Regenerate <cwd>/.atl/skill-registry.md when the skill set changed.
 * Returns { status: 'skipped'|'cache-hit'|'refreshed', count?, path? }.
 */
export async function refreshRegistry({ cwd, claudeHome, gitignore = true, force = false, home } = {}) {
  const dir = path.resolve(cwd ?? process.cwd());
  if (!(await isProjectDir(dir, home))) return { status: 'skipped', reason: 'not a project directory' };
  const { skills, sources } = await collectSkills(dir, claudeHome ?? resolveTargets({}).claudeHome);
  const outFile = path.join(dir, '.atl', 'skill-registry.md');
  const cacheFile = path.join(dir, '.atl', '.skill-registry.cache.json');
  const fp = fingerprint(skills, sources);

  if (!force) {
    const cached = await readFile(cacheFile, 'utf8').then((t) => JSON.parse(t).fingerprint, () => null);
    if (cached === fp && (await exists(outFile))) return { status: 'cache-hit', count: skills.length, path: outFile };
  }
  await mkdir(path.dirname(outFile), { recursive: true });
  const text = renderRegistry({ repoName: path.basename(dir), date: new Date().toISOString().slice(0, 10), sources, skills });
  await writeFileAtomic(outFile, text);
  await writeFileAtomic(cacheFile, `${JSON.stringify({ fingerprint: fp })}\n`);
  if (gitignore) await ensureGitignore(dir);
  return { status: 'refreshed', count: skills.length, path: outFile };
}
