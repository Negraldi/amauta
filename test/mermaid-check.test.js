import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, mkdtemp, writeFile, rm } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractFences, checkMarkdown } from '../src/mermaid/check.js';
import { loadManifest } from '../src/install/assets.js';
import { main } from '../src/cli.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sink = () => { let s = ''; return { write: (x) => { s += x; }, get text() { return s; } }; };
const fence = (src) => `text\n\n\`\`\`mermaid\n${src}\n\`\`\`\n`;

test('the vendored mermaid file matches the pinned sha256 in the manifest and NOTICE', async () => {
  const m = (await loadManifest()).vendored.mermaid;
  const bytes = await readFile(path.join(root, m.path));
  assert.equal(createHash('sha256').update(bytes).digest('hex'), m.sha256);
  assert.equal(m.license, 'MIT');
  const notice = await readFile(path.join(root, 'NOTICE'), 'utf8');
  assert.ok(notice.includes(m.sha256) && notice.includes(`mermaid@${m.version}`));
});

test('extractFences finds backtick and tilde fences, ignores other languages and flags unclosed ones', () => {
  const md = ['```mermaid', 'A-->B', '```', '', '```js', 'x', '```', '~~~mermaid', 'C-->D', '~~~', '```mermaid', 'never closed'].join('\n');
  const f = extractFences(md);
  assert.deepEqual(f.map((x) => [x.line, x.source, x.closed]), [[1, 'A-->B', true], [8, 'C-->D', true], [11, 'never closed', false]]);
});

test('every common diagram type parses without a DOM; broken syntax is reported with its line', async () => {
  const good = ['flowchart TD\n  A["a label"] --> B', 'sequenceDiagram\n  A->>B: hi', 'erDiagram\n  U ||--o{ O : places', 'stateDiagram-v2\n  [*] --> A', 'classDiagram\n  class A\n  A <|-- B',
    'gantt\n  dateFormat YYYY-MM-DD\n  section s\n  T :a1, 2026-01-01, 3d'];
  const r = await checkMarkdown(good.map(fence).join('\n'));
  assert.deepEqual(r.map((x) => x.ok), good.map(() => true), JSON.stringify(r));
  const bad = await checkMarkdown(`intro\n${fence('flowchart TD\n  A --> end')}\n${fence('flowchart TD\n  A -->')}\n${fence('')}`);
  assert.deepEqual(bad.map((x) => x.ok), [false, false, false]);
  assert.equal(bad[0].line, 4);
  assert.match(bad[0].error, /Parse error/);
  assert.match(bad[2].error, /empty/);
});

test('amauta mermaid check: exit 0 for valid files, 1 for invalid, 2 for usage', async () => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'amauta-mmd-'));
  try {
    const ok = path.join(dir, 'ok.md');
    const bad = path.join(dir, 'bad.md');
    await writeFile(ok, fence('flowchart LR\n  A --> B'));
    await writeFile(bad, fence('flowchart LR\n  A -->'));
    const out = sink(); const err = sink();
    assert.equal(await main(['mermaid', 'check', ok], { stdout: out, stderr: err }), 0);
    assert.match(out.text, /ok\.md:3: ok \(flowchart-v2\)/);
    const out2 = sink(); const err2 = sink();
    assert.equal(await main(['mermaid', 'check', ok, bad], { stdout: out2, stderr: err2 }), 1);
    assert.match(err2.text, /bad\.md:3: Parse error/);
    assert.equal(await main(['mermaid', 'check', path.join(dir, 'missing.md')], { stdout: sink(), stderr: sink() }), 1);
    assert.equal(await main(['mermaid'], { stdout: sink(), stderr: sink() }), 2);
    const none = path.join(dir, 'none.md');
    await writeFile(none, '# no diagrams\n');
    const out3 = sink();
    assert.equal(await main(['mermaid', 'check', none], { stdout: out3, stderr: sink() }), 0);
    assert.match(out3.text, /no mermaid fences/);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('diagrams generated by the portal from hostile labels are valid mermaid and stay one node per item', async () => {
  const script = `
import json
from python.amauta.portal import diagrams
H = ['x"]\\n  click n0 call alert(1)\\n  n9["y', "<img src=x onerror=alert(1)>", "\`back\` [a] (b) {c} | d ; e # f % g & h \\\\ i", "end", "graph TD", "%% comment", "a --> b", ":::cls", "tab\\there\\x00"]
hs = {"installed": True, "version": H[0], "persona": H[1], "rdd_mode": H[2], "skills": 3, "agents": 2,
      "hooks": [{"event": t, "kind": "other"} for t in H], "mcp_servers": [{"name": t, "type": H[1], "command": "c"} for t in H]}
out = [diagrams.architecture(hs, H[2]), diagrams.odd_progress(H[0], [{"done": i % 2 == 0, "title": t} for i, t in enumerate(H)])]
nodes = [{"id": f"i{i}", "label": t, "kind": H[1], "file": H[2], "depth": 0 if i == 0 else 1} for i, t in enumerate(H)]
out.append(diagrams.graph_neighborhood({"start": ["i0"], "nodes": nodes, "edges": [{"src": "i0", "dst": f"i{i}", "relation": t} for i, t in enumerate(H)]}))
print(json.dumps(out))
`;
  const r = spawnSync('python3', ['-P', '-c', script], { cwd: root, encoding: 'utf8', env: { ...process.env, PYTHONPATH: root } });
  assert.equal(r.status, 0, r.stderr);
  const sources = JSON.parse(r.stdout);
  assert.equal(sources.length, 3);
  const results = await checkMarkdown(sources.map(fence).join('\n'));
  assert.deepEqual(results.map((x) => x.ok), [true, true, true], JSON.stringify(results));
});
